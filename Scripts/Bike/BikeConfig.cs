using UnityEngine;

namespace BikeGame
{
    /// <summary>
    /// Все настройки физики велосипеда и гонщика в одном файле-ассете. Единицы — реальные: кг, Н, Н·м, Вт, м.
    /// Создать: ПКМ в Project → Create → Bike → Bike Config.
    /// Значения можно менять прямо во время Play — байк подхватит их сразу.
    /// Числа подобраны по расчёту (Tools/physics/bike_sim.py): разгон, мэнуал, вилли, тормоза, приземления, подъёмы.
    /// </summary>
    [CreateAssetMenu(menuName = "Bike/Bike Config", fileName = "BikeConfig")]
    public class BikeConfig : ScriptableObject
    {
        /// <summary>Версия набора значений по умолчанию. Сборщик сцены обновляет старые ассеты.</summary>
        public const int CurrentVersion = 32;   // 26 — физика как в жизни: земная гравитация, сила ног реального райдера, полёт по сохранению момента; 27 — вращение в банни-хопе задаёт толчок, рывок на краю кикера — по заднему колесу; 28 — сальто как в Mountain Bike Xtreme; 29 — сальто с инерцией; 30 — вилли держит игрок, мягкая подвеска, рама ломается; 31 — сильнее ноги (2000 Н·м, 1800/2000 Вт), сальто 250 °/с, рама разламывается пополам; 32 — переднее колесо 0.9 кг
        [HideInInspector] public int version = CurrentVersion;

        [Header("Массы (кг) и инерция (кг·м²)")]
        [Tooltip("Рама с вилкой, амортизатором, рулём, седлом.")]
        public float frameMass = 13f;
        [Tooltip("Центр масс рамы (локально, м).")]
        public Vector2 frameCenterOfMass = new Vector2(-0.05f, 0.30f);
        public float frameInertia = 1.3f;
        [Tooltip("Гонщик. Отдельное тело на «мышцах» — его вес давит на байк там, где он стоит.")]
        public float riderMass = 72f;
        public float riderInertia = 7f;
        [Range(0f, 1f)]
        [Tooltip("Какая доля инерции тела гонщика поворачивается вместе с рамой (руки и ноги на руле и педалях).")]
        public float riderInertiaCoupling = 0.3f;
        [Tooltip("Насколько жёстко гонщик держит байк (руки на руле, ноги на педалях): доля его массы × плечо², которая поворачивается вместе с рамой. Больше — байк вращается медленнее, вилли и дропы спокойнее.")]
        public float riderRigidity = 1.5f;
        [Tooltip("Колесо в сборе (шина, обод, спицы, ротор).")]
        public float wheelMass = 5f;
