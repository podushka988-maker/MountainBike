                 "сохраняется (частота пружины пересчитывается под лёгкое колесо). Лёгкий перед проще поднять и легче подбрасывает на кочках.")]
        public float frontWheelMass = 18f;
        public float FrontWheelMass => frontWheelMass > 0f ? frontWheelMass : wheelMass;
        public float FrontWheelInertia => wheelInertia * FrontWheelMass / Mathf.Max(0.01f, wheelMass);
        public float WheelsMass => wheelMass + FrontWheelMass;
        [Tooltip("Множитель гравитации для байка и гонщика. 1 — земная (9.81 м/с²), как в жизни. Раньше была «лёгкая» 0.747.")]
        public float gravityScale = 1f;
        [Tooltip("Внутренний масштаб масс для физического движка (законы движения от него не зависят). Не трогайте.")]
        public float massScale = 0.05f;

        [Header("Педали")]
        [Tooltip("Наибольший момент ног на шатунах (стоя, на малом каденсе), Н·м. В жизни у сильного райдера ~220; по умолчанию 2000 — аркадно сильные ноги (быстрый разгон, перед легко поднимается). На заднем колесе делится на передаточное число.")]
        public float crankTorque = 2000f;
        [Tooltip("Длительная мощность ног, Вт (в жизни сильный райдер ~400, по умолчанию 1800). На скорости сила падает как P / ω; предел скорости на передаче — каденс.")]
        public float pedalPower = 1800f;
        [Tooltip("Мощность ног в рывке (первые секунды педалирования), Вт (в жизни ~1300, по умолчанию 2000).")]
        public float pedalPeakPower = 2000f;
        [Tooltip("За сколько секунд рывок ног спадает к длительной мощности, с.")]
        public float peakPowerTime = 10f;
