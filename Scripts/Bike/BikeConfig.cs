        public int chainring = 32;
        [Tooltip("Зубья звёзд кассеты: от 1-й передачи (самая лёгкая, большая звезда) до 11-й (самая тяжёлая, самая быстрая).")]
        public int[] cassette = { 46, 37, 32, 28, 25, 22, 19, 17, 15, 13, 11 };
        [Tooltip("Передача на старте заезда.")]
        public int startGear = 5;
        [Tooltip("Каденс, об/мин: до первого числа ноги давят в полную силу, к второму уже не успевают — передача «кончилась», пора переключаться вверх.")]
        public float cadenceFull = 100f, cadenceMax = 150f;
        [Tooltip("Переключение под нагрузкой: сколько секунд цепь перескакивает на другую звезду, с.")]
        public float shiftTime = 0.15f;
        [Range(0f, 1f)]
        [Tooltip("Какая доля силы ног доходит до колеса, пока цепь перескакивает.")]
        public float shiftTorque = 0.3f;

        [Header("Тормоза (Н·м на колесе)")]
        [Tooltip("Передний тормоз — его предел. Сколько из него взять, решает гонщик: изо всех сил, но так, чтобы не перелететь через руль (см. «Передний тормоз и стоппи»).")]
        public float brakeFront = 320f;
        [Tooltip("Задний тормоз. Им же гонщик ловит вилли, когда перед уходит за точку баланса; S на заднем колесе — перед резко на землю.")]
        public float brakeRear = 200f;

        [Header("Передний тормоз и стоппи (рефлексы гонщика)")]
        [Tooltip("S: гонщик тормозит передним изо всех сил, пока зад не поднимется на Endo Lift° (вес посередине); к Endo Lift + Endo Range отпускает совсем. Упреждение, с. Заднее колесо при этом заблокировано.")]
        public float endoLift = 2f, endoRange = 2f, endoPredict = 0.25f;
        [Tooltip("Насколько зад может оторваться при торможении, °: с весом вперёд (D + S — зад поднимается, как в жизни) и с весом назад (A + S — зад на земле, юзом).")]
        public float endoLiftForward = 11f, endoLiftBack = 0.2f;
        [Tooltip("D + S — стоппи: гонщик держит зад поднятым примерно на этот угол, °; дозирует передний тормоз за Stoppie Range°, упреждение, с.")]
        public float stoppieLift = 18f, stoppieRange = 6f, stoppiePredict = 0.25f;
        [Tooltip("Стоппи: зад поднялся больше чем на Stoppie Lift + это, ° — гонщик спасается и отпускает передний тормоз.")]
        public float stoppieRescue = 12f;
        [Tooltip("Стоппи — только быстрее этого, м/с (на месте зад опускается).")]
        public float stoppieMinSpeed = 1.5f;
        [Tooltip("Старое авто-стоппи: гонщик сам держит зад у Stoppie Lift°. Работает, только если Stoppie Manual выключен.")]
        public bool stoppieWithForward = false;
        [Tooltip("СТОППИ ДОЗИРУЕТ ИГРОК: D + S — передний тормоз без подстраховки гонщика. Нажим растёт, пока держишь S " +
                 "(Front Squeeze Time до полного), зад поднимается; зажал надолго — перелёт через руль. Отпустил S — нажим падает " +
                 "за Front Release Time, зад опускается; отпустил D — гонщик снова сам дозирует тормоз.")]
