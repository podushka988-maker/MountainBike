        public float frontSqueezeTime = 0.6f, frontReleaseTime = 0.1f;

        [Header("Рывок ногами вперёд (D)")]
        [Tooltip("Свежий бросок веса вперёд (D), оба колеса на земле: ноги подтягивают зад — он отрывается примерно на " +
