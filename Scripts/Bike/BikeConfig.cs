        [Tooltip("За сколько секунд нарастает усилие ног после нажатия газа.")]
        public float pedalEffortRise = 0.25f;
        [Tooltip("Предохранитель: быстрее этого, градусов/сек, педали колесо не раскручивают (≈ 160 км/ч, на деле не достигается).")]
        public float maxWheelSpeed = 7200f;
        [Tooltip("Если байк едет назад при нажатии газа — включите.")]
        public bool invertMotor = false;

        [Header("Передачи (1×11: одна звезда у педалей, кассета 11–46 на заднем колесе)")]
